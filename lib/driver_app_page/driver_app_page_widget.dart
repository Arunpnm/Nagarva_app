/// Transport › Driver app (Claude Design handoff, screen `drv`): one trip
/// at a time — start and end odometer, Start / End trip, fuel and toll
/// entries, and the trip's km and spend.
///
/// Works on the tables Trips already uses: `trips` (km_start, km_end,
/// status planned → ongoing → completed; total_km is generated by the
/// database) and `trip_expenses` (paid_by `driver`).
///
/// A driver's own session sees only trips naming them (driver_phone, or
/// driver_name when no phone was entered). Owners and managers pick any
/// planned or ongoing trip.
///
/// Not built: the design's Advance tile. Driver advances are kept per
/// order and staff member (job_expense_floats), not per trip, so there is
/// nothing truthful to show as "advance left" on a trip.
class DriverAppPage extends StatefulWidget {
  const DriverAppPage({super.key});

  static const routeName = 'DriverAppPage';
  static const routePath = '/driver-app';

  @override
  State<DriverAppPage> createState() => _DriverAppPageState();
}

class _DriverAppPageState extends State<DriverAppPage> {
  List<TripsRow> _trips = const [];
  String? _tripId;
  List<TripExpensesRow> _expenses = const [];
  bool _loading = true;
  bool _busy = false;
  final _start = TextEditingController();
  final _end = TextEditingController();

  static final _money =
      NumberFormat.currency(locale: 'en_IN', symbol: '₹', decimalDigits: 0);

  bool get _isDriver =>
      AppSession.instance.currentStaffId != null &&
      AppSession.instance.currentStaffRole == 'driver';

  TripsRow? get _trip =>
      _trips.where((t) => t.id == _tripId).firstOrNull ?? _trips.firstOrNull;

  @override
  void initState() {
    super.initState();
    _load();
  }

  @override
  void dispose() {
    _start.dispose();
    _end.dispose();
    super.dispose();
  }

  Future<void> _load() async {
    try {
      var trips = await TripsTable().queryRows(
        queryFn: (q) => OrgScope.read(q)
            .inFilter('status', ['planned', 'ongoing'])
            .order('start_date'),
      );
      if (_isDriver) {
        final me = await StaffTable().queryRows(
          queryFn: (q) =>
              OrgScope.read(q).eq('id', AppSession.instance.currentStaffId!),
        );
        final phone = _digits(me.firstOrNull?.phone);
        final name = (me.firstOrNull?.name ?? '').trim().toLowerCase();
        trips = trips.where((t) {
          final tp = _digits(t.driverPhone);
          if (tp.isNotEmpty && phone.isNotEmpty) {
            return tp.endsWith(phone) || phone.endsWith(tp);
          }
          return name.isNotEmpty &&
              (t.driverName ?? '').trim().toLowerCase() == name;
        }).toList();
      }
      // An ongoing trip first: that is the one being driven.
      trips.sort((a, b) => (a.status == 'ongoing' ? 0 : 1)
          .compareTo(b.status == 'ongoing' ? 0 : 1));
      _trips = trips;
      final t = _trip;
      _tripId = t?.id;
      _start.text = t?.kmStart?.toString() ?? '';
      _end.text = t?.kmEnd?.toString() ?? '';
      _expenses = t?.id == null
          ? const []
          : await TripExpensesTable().queryRows(
              queryFn: (q) => OrgScope.read(q)
                  .eq('trip_id', t!.id!)
                  .order('created_at', ascending: false),
            );
    } catch (_) {
      // An empty screen with the "no trip" message rather than a crash.
    }
    if (mounted) setState(() => _loading = false);
  }

  static String _digits(String? s) =>
      (s ?? '').replaceAll(RegExp(r'[^0-9]'), '');

  void _toast(String s) {
    if (!mounted) return;
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(content: Text(s)));
  }

  Future<void> _startOrEnd(TripsRow t) async {
    final l = AppLocalizations.of(context);
    final ongoing = t.status == 'ongoing';
    final start = int.tryParse(_start.text.trim());
    final end = int.tryParse(_end.text.trim());
    if (start == null) return _toast(l.drvNeedStart);
    if (ongoing && (end == null || end <= start)) return _toast(l.drvNeedEnd);
    final today = DateTime.now().toIso8601String().split('T').first;
    setState(() => _busy = true);
    try {
      await TripsTable().update(
        data: ongoing
            ? {
                'km_start': start,
                'km_end': end,
                'end_date': today,
                'status': 'completed',
                'updated_at': DateTime.now().toUtc().toIso8601String(),
              }
            : {
                'km_start': start,
                'status': 'ongoing',
                'updated_at': DateTime.now().toUtc().toIso8601String(),
              },
        matchingRows: (q) => OrgScope.write(q).eq('id', t.id!),
      );
      if (ongoing) _toast(l.drvDone);
      await _load();
    } catch (e) {
      _toast('$e');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  Future<void> _addEntry(TripsRow t, String type) async {
    final l = AppLocalizations.of(context);
    final res = await showDialog<(double, String, double?)>(
      context: context,
      builder: (ctx) => _EntryDialog(fuel: type == 'fuel'),
    );
    if (res == null || t.id == null) return;
    final (amount, place, litres) = res;
    try {
      await TripExpensesTable().insert({
        ...OrgScope.stamp(),
        'trip_id': t.id,
        'expense_type': type,
        'amount': amount,
        if (litres != null) 'quantity': litres,
        if (place.isNotEmpty) 'location': place,
        'paid_by': 'driver',
        'expense_date': DateTime.now().toIso8601String().split('T').first,
      });
      await _load();
    } catch (e) {
      _toast(l.dwSaveFailed);
    }
  }

  @override
  Widget build(BuildContext context) {
    final c = NgPalette.of(context);
    final l = AppLocalizations.of(context);
    final t = _trip;
    return Scaffold(
      backgroundColor: c.bg,
      appBar: NgTopBar(onRefresh: _load),
      body: _loading
          ? const Center(child: CircularProgressIndicator())
          : RefreshIndicator(
              onRefresh: _load,
              child: ListView(
                padding: const EdgeInsets.fromLTRB(16, 14, 16, 32),
                children: [
                  NgModuleHeader(
                    l.drvTitle,
                    subtitle: t == null
                        ? null
                        : [
                            if ((t.driverName ?? '').isNotEmpty) t.driverName!,
                            if ((t.vehicleNo ?? '').isNotEmpty) t.vehicleNo!,
                          ].join(' · '),
                  ),
                  const SizedBox(height: 14),
                  if (t == null)
                    NgEmptyState(
                      icon: Icons.local_shipping_outlined,
                      title: l.drvNone,
                    )
                  else ...[
                    if (!_isDriver && _trips.length > 1) ...[
                      SingleChildScrollView(
                        scrollDirection: Axis.horizontal,
                        child: Row(children: [
                          for (final x in _trips)
                            Padding(
                              padding: const EdgeInsets.only(right: 6),
                              child: NgChip(
                                label: x.tripNo ?? x.vehicleNo ?? '—',
                                selected: x.id == t.id,
                                onTap: () {
                                  _tripId = x.id;
                                  _load();
                                },
                              ),
                            ),
                        ]),
                      ),
                      const SizedBox(height: 10),
                    ],
                    _tripCard(c, l, t),
                    const SizedBox(height: 12),
                    _stats(c, l, t),
                    const SizedBox(height: 18),
                    NgSectionHeader(l.drvToday),
                    const SizedBox(height: 8),
                    ..._todayRows(c, l),
                  ],
                ],
              ),
            ),
    );
  }

  Widget _tripCard(NgPalette c, AppLocalizations l, TripsRow t) {
    final ongoing = t.status == 'ongoing';
    InputDecoration dec(String hint) => InputDecoration(
          hintText: hint,
          isDense: true,
          filled: true,
          fillColor: c.inset,
          border: OutlineInputBorder(
            borderRadius: BorderRadius.circular(NgRadius.field),
            borderSide: BorderSide(color: c.w1),
          ),
          enabledBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(NgRadius.field),
            borderSide: BorderSide(color: c.w1),
          ),
        );
    Widget odo(String label, TextEditingController ctrl, bool enabled) =>
        Expanded(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(label, style: NgFonts.geist(fontSize: 12.5, color: c.mute)),
              const SizedBox(height: 6),
              TextField(
                controller: ctrl,
                enabled: enabled,
                keyboardType: TextInputType.number,
                inputFormatters: [FilteringTextInputFormatter.digitsOnly],
                style: NgFonts.mono(fontSize: 15, color: c.text),
                decoration: dec('km'),
              ),
            ],
          ),
        );
    Widget tile(IconData icon, String label, VoidCallback onTap) => Expanded(
          child: Material(
            color: c.s2,
            borderRadius: BorderRadius.circular(14),
            child: InkWell(
              borderRadius: BorderRadius.circular(14),
              onTap: onTap,
              child: Padding(
                padding: const EdgeInsets.symmetric(vertical: 14),
                child: Column(children: [
                  Icon(icon, color: c.acc),
                  const SizedBox(height: 6),
                  Text(label,
                      style: NgFonts.geist(
                          fontSize: 13.5,
                          fontWeight: FontWeight.w600,
                          color: c.text)),
                ]),
              ),
            ),
          ),
        );
    return NgCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(children: [
            Icon(Icons.local_shipping_outlined, color: c.acc, size: 26),
            const SizedBox(width: 10),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text('${t.fromLoc ?? '—'} → ${t.toLoc ?? '—'}',
                      style: NgFonts.geist(
                          fontSize: 16,
                          fontWeight: FontWeight.w600,
                          color: c.text)),
                  Text(
                    [
                      if ((t.tripNo ?? '').isNotEmpty) t.tripNo!,
                      if (t.startDate != null)
                        DateFormat('d MMM').format(t.startDate!),
                    ].join(' · '),
                    style: NgFonts.geist(fontSize: 12.5, color: c.mute),
                  ),
                ],
              ),
            ),
            NgPill(ongoing ? l.drvOngoing : l.drvPlanned,
                status: ongoing ? NgStatus.accent : NgStatus.blue),
          ]),
          const SizedBox(height: 14),
          Row(children: [
            odo(l.drvOdoStart, _start, !ongoing),
            const SizedBox(width: 10),
            odo(l.drvOdoEnd, _end, ongoing),
          ]),
          const SizedBox(height: 12),
          NgPrimaryButton(
            label: ongoing ? l.drvEnd : l.drvStart,
            icon: ongoing ? Icons.flag_outlined : Icons.play_arrow_rounded,
            onPressed: _busy ? null : () => _startOrEnd(t),
          ),
          if (ongoing) ...[
            const SizedBox(height: 10),
            Row(children: [
              tile(Icons.local_gas_station_outlined, l.drvFuel,
                  () => _addEntry(t, 'fuel')),
              const SizedBox(width: 10),
              tile(Icons.toll_outlined, l.drvToll,
                  () => _addEntry(t, 'toll')),
            ]),
          ],
        ],
      ),
    );
  }

  Widget _stats(NgPalette c, AppLocalizations l, TripsRow t) {
    final spend = _expenses.fold<double>(0, (s, e) => s + e.amount);
    return Row(children: [
      Expanded(
        child: NgStatTile(
          icon: Icons.route_outlined,
          label: l.drvTripKm,
          value: t.totalKm == null ? '—' : '${t.totalKm}',
        ),
      ),
      const SizedBox(width: 10),
      Expanded(
        child: NgStatTile(
            icon: Icons.payments_outlined,
            label: l.drvTripSpend,
            value: _money.format(spend)),
      ),
    ]);
  }

  List<Widget> _todayRows(NgPalette c, AppLocalizations l) {
    final now = DateTime.now();
    final today = _expenses.where((e) {
      final d = e.expenseDate;
      return d != null &&
          d.year == now.year &&
          d.month == now.month &&
          d.day == now.day;
    }).toList();
    if (today.isEmpty) return const [];
    return [
      NgCardList(children: [
        for (final e in today)
          NgListRow(
            icon: e.expenseType == 'toll'
                ? Icons.toll_outlined
                : Icons.local_gas_station_outlined,
            title: [
              e.expenseType == 'toll' ? l.drvToll : l.drvFuel,
              if ((e.location ?? '').isNotEmpty) e.location!,
            ].join(' · '),
            subtitle: e.paidBy,
            trailing: Text(_money.format(e.amount),
                style: NgFonts.mono(fontSize: 14, color: c.text)),
          ),
      ]),
    ];
  }
}

class _EntryDialog extends StatefulWidget {
  const _EntryDialog({required this.fuel});
  final bool fuel;

  @override
  State<_EntryDialog> createState() => _EntryDialogState();
}

class _EntryDialogState extends State<_EntryDialog> {
  final _amount = TextEditingController();
  final _place = TextEditingController();
  final _litres = TextEditingController();
  String? _err;

  @override
  void dispose() {
    _amount.dispose();
    _place.dispose();
    _litres.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final l = AppLocalizations.of(context);
    final c = NgPalette.of(context);
    final num = [FilteringTextInputFormatter.allow(RegExp(r'[0-9.]'))];
    return AlertDialog(
      title: Text(widget.fuel ? l.drvFuelT : l.drvTollT),
      content: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          TextField(
            controller: _amount,
            keyboardType: const TextInputType.numberWithOptions(decimal: true),
            inputFormatters: num,
            decoration: const InputDecoration(labelText: '₹'),
          ),
          if (widget.fuel)
            TextField(
              controller: _litres,
              keyboardType:
                  const TextInputType.numberWithOptions(decimal: true),
              inputFormatters: num,
              decoration: InputDecoration(labelText: l.drvLitres),
            ),
          TextField(
            controller: _place,
            decoration: InputDecoration(labelText: l.drvPlaza),
          ),
          if (_err != null) ...[
            const SizedBox(height: 8),
            Text(_err!, style: NgFonts.geist(fontSize: 12.5, color: c.red)),
          ],
        ],
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: Text(MaterialLocalizations.of(context).cancelButtonLabel),
        ),
        TextButton(
          onPressed: () {
            final a = double.tryParse(_amount.text.trim());
            if (a == null || a <= 0) {
              setState(() => _err = l.drvNeedAmount);
              return;
            }
            Navigator.pop(context, (
              a,
              _place.text.trim(),
              double.tryParse(_litres.text.trim()),
            ));
          },
          child: Text(l.drvAdd),
        ),
      ],
    );
  }
}
