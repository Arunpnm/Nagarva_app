      data: {'supervisor_status': 'approved'},
      matchingRows: (q) => OrgScope.write(q).eq('id', order.id!),
    );
    await OrderTrackingTable().insert({
      ...OrgScope.stamp(),
      'order_id': order.id,
      'status': order.status ?? 'delivered',
      'note': 'âœ… Supervisor entries approved by owner/manager',
